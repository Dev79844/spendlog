/**
 * CSV interchange format for expenses, income, categories and recurring rules.
 *
 * Pure TypeScript whose only runtime import is the pure `./date`, so it runs
 * under plain Node (`npm test`) as well as in the app. All database access
 * lives in `lib/db/csv.ts`.
 *
 * Format: one UTF-8 file (with BOM), RFC 4180 quoting, CRLF line endings.
 * `record_type` says what a row is:
 *   expense, income                         one transaction
 *   category, income_category               one category, including unused and
 *                                           deleted (inactive) ones
 *   recurring_expense, recurring_income     one recurring rule; `date` is its
 *                                           start date, `id` its id in the file
 * Transactions come first, then categories, then rules, so the export is a
 * complete backup in a single file the share sheet can send. Rows generated by
 * a rule carry the rule's file id in `recurring_rule_id` and the occurrence
 * day in `occurrence_date`. The columns after `category_active` were added
 * with income; files without them (older exports, hand-made sheets) import as
 * before, and a row without `record_type` is still an expense.
 * The database stores epoch milliseconds (see lib/date.ts). Export converts
 * them to `YYYY-MM-DD` dates (local calendar day) and ISO 8601 UTC
 * timestamps, the stable interchange format. Import is lenient about date and
 * time formats and converts every value back to epoch ms with the same
 * parsers the schema migration uses, so imported rows are stored exactly like
 * migrated ones.
 */

import { parseExpenseDay, parseTimestamp, toDayKey } from './date';
import type { Frequency, TransactionKind } from './types';

