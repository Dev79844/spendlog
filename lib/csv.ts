const BOM = '﻿';

// ---------------------------------------------------------------------------
// Low-level CSV

export function escapeCsvField(value: string): string {
  if (/[",\r\n]/.test(value) || value !== value.trim()) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

export function serializeCsv(rows: string[][]): string {
  return rows.map((row) => row.map(escapeCsvField).join(',')).join('\r\n') + '\r\n';
}

/**
 * Parses RFC 4180 CSV: quoted fields with `""` escapes and embedded
 * newlines, CRLF / LF / CR line endings, optional UTF-8 BOM. Blank lines are
 * skipped. Throws on an unterminated quoted field.
 */
export function parseCsv(text: string): string[][] {
  const input = text.startsWith(BOM) ? text.slice(1) : text;
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;
  let quoted = false; // current field started with a quote
  let rowQuoted = false; // current row has a quoted field (so it isn't blank)

  const endField = () => {
    row.push(field);
    field = '';
    quoted = false;
  };
  const endRow = () => {
    endField();
    const blank = row.length === 1 && row[0] === '' && !rowQuoted;
    if (!blank) rows.push(row);
    row = [];
    rowQuoted = false;
  };

  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (inQuotes) {
      if (ch !== '"') field += ch;
      else if (input[i + 1] === '"') {
        field += '"';
        i++;
      } else inQuotes = false;
    } else if (ch === '"' && field === '' && !quoted) {
      inQuotes = true;
      quoted = true;
      rowQuoted = true;
    } else if (ch === ',') {
      endField();
    } else if (ch === '\r' || ch === '\n') {
      if (ch === '\r' && input[i + 1] === '\n') i++;
      endRow();
    } else {
      // Text after a closing quote (`"a"b`) is kept literally, as most readers do.
      field += ch;
    }
  }
  if (inQuotes) {
    throw new Error('Unterminated quoted field: the file looks truncated or malformed.');
  }
  if (field !== '' || row.length > 0 || quoted) endRow();
  return rows;
}

// ---------------------------------------------------------------------------
// Values

const AMOUNT_RE = /^(\d+(\.\d*)?|\.\d+)$/;
const COLOR_RE = /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;

/** Returns the amount as a number, or null unless it is a plain positive decimal. */
export function parseAmount(value: string): number | null {
  const trimmed = value.trim();
  if (!AMOUNT_RE.test(trimmed)) return null;
  const n = Number(trimmed);
  return Number.isFinite(n) && n > 0 ? n : null;
}

// ---------------------------------------------------------------------------
// Dates and timestamps
//
// Import is lenient so files from older and newer app versions, and sheets
// re-saved by a spreadsheet, still load. The accepted formats and the parsing
// live in lib/date.ts (parseExpenseDay / parseTimestamp), shared with the
// schema migration.

export const ACCEPTED_DATE_FORMATS =
  'YYYY-MM-DD, an ISO 8601 date-time (2026-05-27T09:57:00Z, with an offset like +05:30, or no zone for local time), YYYY-MM-DD HH:MM:SS (UTC), or epoch seconds (10 digits) / milliseconds (13 digits)';

const SLASHED_DMY_RE = /^\d{1,2}[/.-]\d{1,2}[/.-]\d{2,4}$/;

/** A `date` value as the local calendar day `YYYY-MM-DD`. Null if unparseable. */
export function parseDateValue(value: string): string | null {
  const ms = parseExpenseDay(value);
  return ms === null ? null : toDayKey(ms);
}

/** A timestamp value as ISO 8601 UTC. Null if unparseable. */
export function toIsoTimestamp(value: string): string | null {
  const ms = parseTimestamp(value);
  return ms === null ? null : new Date(ms).toISOString();
}

/** The error for an unparseable date or timestamp in `column`. */
export function dateValueError(column: string, value: string): string {
  const reason = SLASHED_DMY_RE.test(value.trim())
    ? "is ambiguous: day/month order can't be told apart safely"
    : 'is not a recognised date';
  return `${column} "${value}" ${reason}. Use ${ACCEPTED_DATE_FORMATS}.`;
}

/** `spendlog-export-YYYYMMDD-HHMM.csv` in local time. */
export function exportFileName(now: Date): string {
  const p = (n: number) => String(n).padStart(2, '0');
  const date = `${now.getFullYear()}${p(now.getMonth() + 1)}${p(now.getDate())}`;
  return `spendlog-export-${date}-${p(now.getHours())}${p(now.getMinutes())}.csv`;
}

/**
 * Identity of an expense for duplicate detection on import: same date, amount,
 * category (case-insensitive) and description.
 */
export function expenseDuplicateKey(e: {
  date: number;
  amount: number;
  category: string;
  description: string | null;
}): string {
  return JSON.stringify([toDayKey(e.date), e.amount, e.category.trim().toLowerCase(), e.description ?? '']);
}

/** Identity of a recurring rule for duplicate detection on import. */
export function ruleDuplicateKey(r: {
  kind: TransactionKind;
  start_date: number;
  amount: number;
  category: string;
  description: string | null;
  frequency: Frequency;
  interval: number;
}): string {
  return JSON.stringify([
    r.kind,
    toDayKey(r.start_date),
    r.amount,
    r.category.trim().toLowerCase(),
    r.description ?? '',
    r.frequency,
    r.interval,
  ]);
}

// ---------------------------------------------------------------------------
// Export

export function buildExportCsv(data: CsvExportData): string {
  const ts = (v: number | null) => (v === null ? '' : new Date(v).toISOString());
  const day = (v: number | null | undefined) => (v === null || v === undefined ? '' : toDayKey(v));
  const rows: string[][] = [[...CSV_COLUMNS]];
  const empty = Object.fromEntries(CSV_COLUMNS.map((c) => [c, ''])) as Record<CsvColumn, string>;
  const push = (record: Partial<Record<CsvColumn, string>>) => {
    const full = { ...empty, ...record };
    rows.push(CSV_COLUMNS.map((c) => full[c]));
  };

  const transactions: [TransactionKind, CsvExportExpense[]][] = [
    ['expense', data.expenses],
    ['income', data.incomes],
  ];
  for (const [kind, list] of transactions) {
    for (const e of list) {
      push({
        id: String(e.id),
        date: toDayKey(e.date),
        amount: String(e.amount),
        category: e.category,
        category_color: e.category_color ?? '',
        category_icon: e.category_icon ?? '',
        location: e.location ?? '',
        description: e.description ?? '',
        metadata: e.metadata ?? '',
        created_at: ts(e.created_at),
        updated_at: ts(e.updated_at),
        record_type: kind,
        recurring_rule_id: e.recurring_rule_id == null ? '' : String(e.recurring_rule_id),
        occurrence_date: day(e.occurrence_date),
      });
    }
  }

  const categoryLists: [string, CsvExportCategory[]][] = [
    ['category', data.categories],
    ['income_category', data.incomeCategories],
  ];
  for (const [recordType, list] of categoryLists) {
    for (const c of list) {
      push({
        category: c.name,
        category_color: c.color ?? '',
        category_icon: c.icon ?? '',
        created_at: ts(c.created_at),
        record_type: recordType,
        category_active: c.is_active === 1 ? '1' : '0',
      });
    }
  }

  for (const r of data.rules) {
    push({
      id: String(r.id),
      date: toDayKey(r.start_date),
      amount: String(r.amount),
      category: r.category,
      category_color: r.category_color ?? '',
      category_icon: r.category_icon ?? '',
      location: r.location ?? '',
      description: r.description ?? '',
      created_at: ts(r.created_at),
      updated_at: ts(r.updated_at),
      record_type: `recurring_${r.kind}`,
      frequency: r.frequency,
      interval: String(r.interval),
      end_date: day(r.end_date),
      rule_active: r.is_active === 1 ? '1' : '0',
      last_occurrence: day(r.last_occurrence),
    });
  }

  return BOM + serializeCsv(rows);
}

// ---------------------------------------------------------------------------
// Import

const HEADER_ALIASES: Record<string, CsvColumn> = {
  category_name: 'category',
  type: 'record_type',
};

const FREQUENCIES: readonly Frequency[] = ['daily', 'weekly', 'monthly', 'yearly'];

const RECORD_TYPES = [
  'expense',
  'income',
  'category',
  'income_category',
  'recurring_expense',
  'recurring_income',
] as const;
type RecordType = (typeof RECORD_TYPES)[number];

function normaliseHeader(h: string): string {
  return h.trim().toLowerCase().replace(/[\s-]+/g, '_');
}

/** 1/0 style flag; empty means `fallback`. Null when unrecognised. */
function parseFlag(value: string, fallback: number): number | null {
  const v = value.toLowerCase();
  if (v === '') return fallback;
  if (['1', 'true', 'yes'].includes(v)) return 1;
  if (['0', 'false', 'no'].includes(v)) return 0;
  return null;
}

/**
 * Parses and validates an import file. Accepts the app's own export as well as
 * a hand-made sheet with at least `date`, `amount` and `category` columns (in
 * any order; unknown columns are ignored). Rows without `record_type` are
 * expenses. Any error should block the whole import.
 */
export function parseImportCsv(text: string): CsvImportResult {
  const result: CsvImportResult = { expenses: [], incomes: [], categories: [], rules: [], errors: [] };

  let records: string[][];
  try {
    records = parseCsv(text);
  } catch (error) {
    result.errors.push({ row: 0, message: (error as Error).message });
    return result;
  }
  if (records.length === 0) {
    result.errors.push({ row: 0, message: 'The file is empty.' });
    return result;
  }

  const index = new Map<CsvColumn, number>();
  records[0].forEach((raw, i) => {
    const name = normaliseHeader(raw);
    const column = (CSV_COLUMNS as readonly string[]).includes(name)
      ? (name as CsvColumn)
      : HEADER_ALIASES[name];
    if (column && !index.has(column)) index.set(column, i);
  });
  const missing = (['date', 'amount', 'category'] as const).filter((c) => !index.has(c));
  if (missing.length > 0) {
    result.errors.push({
      row: 1,
      message: `Missing column${missing.length > 1 ? 's' : ''}: ${missing.join(', ')}.`,
    });
    return result;
  }

  const seenCategories = new Set<string>();
  const seenRuleIds = new Set<string>();

  records.slice(1).forEach((fields, i) => {
    const row = i + 2;
    // Free text (names, location, description, metadata) is kept exactly;
    // structured values are trimmed.
    const raw = (c: CsvColumn) => {
      const at = index.get(c);
      return at === undefined ? '' : (fields[at] ?? '');
    };
    const get = (c: CsvColumn) => raw(c).trim();
    const text = (c: CsvColumn) => raw(c) || null;
    const errors: string[] = [];

    const timestamp = (c: CsvColumn) => {
      const raw = get(c);
      if (!raw) return null;
      const ms = parseTimestamp(raw);
      if (ms === null) errors.push(dateValueError(c, raw));
      return ms;
    };
    // A calendar day; null when empty (or `required` and reported missing).
    const day = (c: CsvColumn, required = false) => {
      const raw = get(c);
      if (!raw && !required) return null;
      const ms = parseExpenseDay(raw);
      if (ms === null) errors.push(dateValueError(c, raw));
      return ms;
    };
    const positiveInt = (c: CsvColumn) => {
      const raw = get(c);
      if (!raw) return null;
      if (/^\d+$/.test(raw) && Number(raw) > 0) return Number(raw);
      errors.push(`${c} "${raw}" is not a positive whole number`);
      return null;
    };
    const amountOf = () => {
      const amountRaw = get('amount');
      const amount = parseAmount(amountRaw);
      if (amount === null) errors.push(`amount "${amountRaw}" is not a positive number`);
      return amount;
    };
    const fail = () => errors.forEach((message) => result.errors.push({ row, message }));

    const name = raw('category');
    if (!name.trim()) errors.push('category is empty');
    const color = get('category_color') || null;
    if (color && !COLOR_RE.test(color)) errors.push(`category_color "${color}" is not a hex color`);
    const icon = get('category_icon') || null;

    const type = (get('record_type').toLowerCase() || 'expense') as RecordType;
    if (!RECORD_TYPES.includes(type)) {
      result.errors.push({ row, message: `record_type "${type}" must be one of ${RECORD_TYPES.join(', ')}` });
      return;
    }

    if (type === 'category' || type === 'income_category') {
      const kind: TransactionKind = type === 'category' ? 'expense' : 'income';
      const activeRaw = get('category_active');
      const isActive = parseFlag(activeRaw, 1);
      if (isActive === null) errors.push(`category_active "${activeRaw}" must be 1 or 0`);
      const key = `${kind}:${name.trim().toLowerCase()}`;
      if (name && seenCategories.has(key)) errors.push(`${type} "${name}" is listed twice`);
      seenCategories.add(key);
      const createdAt = timestamp('created_at');

      if (errors.length > 0 || isActive === null) return fail();
      result.categories.push({ row, kind, name, color, icon, is_active: isActive, created_at: createdAt });
      return;
    }

    if (type === 'recurring_expense' || type === 'recurring_income') {
      const kind: TransactionKind = type === 'recurring_expense' ? 'expense' : 'income';
      const startDate = day('date', true);
      const amount = amountOf();
      const frequency = get('frequency').toLowerCase() as Frequency;
      if (!FREQUENCIES.includes(frequency)) {
        errors.push(`frequency "${get('frequency')}" must be one of ${FREQUENCIES.join(', ')}`);
      }
      const interval = positiveInt('interval') ?? 1;
      const endDate = day('end_date');
      if (endDate !== null && startDate !== null && endDate < startDate) {
        errors.push('end_date is before the start date');
      }
      const activeRaw = get('rule_active');
      const isActive = parseFlag(activeRaw, 1);
      if (isActive === null) errors.push(`rule_active "${activeRaw}" must be 1 or 0`);
      const lastOccurrence = day('last_occurrence');
      const id = positiveInt('id');
      if (id !== null) {
        if (seenRuleIds.has(String(id))) errors.push(`recurring rule id ${id} is listed twice`);
        seenRuleIds.add(String(id));
      }
      const createdAt = timestamp('created_at');
      const updatedAt = timestamp('updated_at');

      if (errors.length > 0 || startDate === null || amount === null || isActive === null) return fail();
      result.rules.push({
        row,
        kind,
        id,
        amount,
        category: name,
        category_color: color,
        category_icon: icon,
        location: kind === 'expense' ? text('location') : null,
        description: text('description'),
        frequency,
        interval,
        start_date: startDate,
        end_date: endDate,
        is_active: isActive,
        last_occurrence: lastOccurrence,
        created_at: createdAt,
        updated_at: updatedAt,
      });
      return;
    }

    const kind: TransactionKind = type;
    const date = day('date', true);
    const amount = amountOf();
    const id = positiveInt('id');
    const ruleId = positiveInt('recurring_rule_id');
    const occurrence = day('occurrence_date');
    const createdAt = timestamp('created_at');
    const updatedAt = timestamp('updated_at');

    if (errors.length > 0 || amount === null || date === null) return fail();
    (kind === 'income' ? result.incomes : result.expenses).push({
      row,
      kind,
      id,
      date,
      amount,
      category: name,
      category_color: color,
      category_icon: icon,
      location: kind === 'expense' ? text('location') : null,
      description: text('description'),
      metadata: text('metadata'),
      recurring_rule_id: ruleId,
      occurrence_date: ruleId === null ? null : (occurrence ?? date),
      created_at: createdAt,
      updated_at: updatedAt,
    });
  });

  // A transaction pointing at a rule the file doesn't contain (of its kind)
  // is kept, unlinked.
  const ruleIds = new Set(result.rules.map((r) => `${r.kind}:${r.id}`));
  for (const e of [...result.expenses, ...result.incomes]) {
    if (e.recurring_rule_id !== null && !ruleIds.has(`${e.kind}:${e.recurring_rule_id}`)) {
      e.recurring_rule_id = null;
      e.occurrence_date = null;
    }
  }

  return result;
}
