// Database row types. All dates/times are epoch milliseconds (see lib/date.ts).

// Which table a transaction, category or recurring rule belongs to: expenses
// and `categories`, or incomes and `income_categories`.
export type TransactionKind = 'expense' | 'income';
export interface Category {
  id: number;
  name: string;
  color: string | null;
  icon: string | null;
  is_active: number; // SQLite uses 0/1 for booleans
  created_at: number;
}

export interface Expense {
  id: number;
  amount: number;
  date: number; // calendar day, stored as local noon (toExpenseDay)
  category_id: number;
  location: string | null;
  description: string | null;
  metadata: string | null; // JSON string
  recurring_rule_id: number | null; // set on rows generated by a recurring rule
  occurrence_date: number | null; // the rule's occurrence day this row was generated for
  created_at: number;
  updated_at: number;
}

// Expense with joined category data
export interface ExpenseWithCategory extends Expense {
  category_name: string;
  category_color: string | null;
}

export interface Income {
  id: number;
  amount: number;
  date: number; // calendar day, stored as local noon (toExpenseDay)
  category_id: number; // income_categories.id
  description: string | null;
  metadata: string | null;
  recurring_rule_id: number | null;
  occurrence_date: number | null;
  created_at: number;
  updated_at: number;
}

export interface IncomeWithCategory extends Income {
  category_name: string;
  category_color: string | null;
}

export type Frequency = 'daily' | 'weekly' | 'monthly' | 'yearly';

export interface RecurringRule {
  id: number;
  kind: TransactionKind;
  amount: number;
  category_id: number; // categories.id or income_categories.id, by kind
  location: string | null; // expenses only
  description: string | null;
  frequency: Frequency;
  interval: number; // every `interval` days/weeks/months/years
  start_date: number; // local noon of the first occurrence
  end_date: number | null; // local noon of the last day allowed, inclusive
  is_active: number;
  last_occurrence: number | null; // latest occurrence day already generated
  created_at: number;
  updated_at: number;
}

export interface RecurringRuleWithCategory extends RecurringRule {
  category_name: string | null;
  category_color: string | null;
}

// Input types for creating/updating
export interface CreateExpenseInput {
  amount: number;
  date: number;
  category_id: number;
  location?: string;
  description?: string;
  metadata?: string;
}

export interface UpdateExpenseInput {
  amount?: number;
  date?: number;
  category_id?: number;
  location?: string | null;
  description?: string | null;
  metadata?: string | null;
}

export interface CreateIncomeInput {
  amount: number;
  date: number;
  category_id: number;
  description?: string;
  metadata?: string;
}

export interface UpdateIncomeInput {
  amount?: number;
  date?: number;
  category_id?: number;
  description?: string | null;
  metadata?: string | null;
}

export interface RecurringRuleInput {
  kind: TransactionKind;
  amount: number;
  category_id: number;
  location: string | null;
  description: string | null;
  frequency: Frequency;
  interval: number;
  start_date: number;
  end_date: number | null;
}

export interface CreateCategoryInput {
  name: string;
  color?: string;
  icon?: string;
}

export interface UpdateCategoryInput {
  name?: string;
  color?: string | null;
  icon?: string | null;
  is_active?: number;
}

// Store types
// Category actions take a kind; it defaults to 'expense'.
export interface CategoryState {
  categories: Category[]; // expense categories
  incomeCategories: Category[];
  loading: boolean;
  error: string | null;
  loadCategories: () => Promise<void>;
  addCategory: (input: CreateCategoryInput, kind?: TransactionKind) => Promise<Category>;
  updateCategory: (id: number, input: UpdateCategoryInput, kind?: TransactionKind) => Promise<void>;
  deleteCategory: (id: number, kind?: TransactionKind) => Promise<void>;
  getCategoryById: (id: number, kind?: TransactionKind) => Category | undefined;
}

export interface ExpenseState {
  expenses: ExpenseWithCategory[];
  loading: boolean;
  error: string | null;
  currentMonth: string; // YYYY-MM format
  monthlyTotal: number;
  loadExpenses: (month?: string) => Promise<void>;
  addExpense: (input: CreateExpenseInput) => Promise<Expense>;
  updateExpense: (id: number, input: UpdateExpenseInput) => Promise<void>;
  deleteExpense: (id: number) => Promise<void>;
  setCurrentMonth: (month: string) => void;
}

export interface IncomeState {
  loading: boolean;
  error: string | null;
  addIncome: (input: CreateIncomeInput) => Promise<Income>;
  updateIncome: (id: number, input: UpdateIncomeInput) => Promise<void>;
  deleteIncome: (id: number) => Promise<void>;
}

export interface RecurringState {
  rules: RecurringRuleWithCategory[];
  error: string | null;
  // Bumped whenever a catch-up inserted rows, so focused screens re-query.
  generation: number;
  loadRules: () => void;
  // Generates every due occurrence (idempotent); returns how many rows were added.
  runDue: () => number;
  addRule: (input: RecurringRuleInput) => Promise<RecurringRule>;
  updateRule: (id: number, input: RecurringRuleInput) => Promise<void>;
  setRuleActive: (id: number, active: boolean) => Promise<void>;
  deleteRule: (id: number) => Promise<void>;
}

// Summary types
export interface CategorySummary {
  category_id: number;
  category_name: string;
  category_color: string | null;
  total: number;
  percentage: number;
}

export interface MonthlySummary {
  total: number;
  categories: CategorySummary[];
  expenseCount: number;
}

// An expense day the shifted-dates migration fixed or wants the user to check
// (table date_review, see lib/db/migrations.ts and lib/db/date-review.ts).
export interface DateReviewItem extends ExpenseWithCategory {
  // 'add-shifted': fixed automatically; 'add-uncertain': saved near midnight
  // or near the UTC offset; 'edited': saved by the old edit screen.
  reason: 'add-shifted' | 'add-uncertain' | 'edited';
  status: 'pending' | 'fixed';
  original_date: number; // the day as the old app stored it
  suggested_date: number;
}

